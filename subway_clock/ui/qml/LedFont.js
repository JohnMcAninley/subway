// Lowercase letters without ascenders start 3 rows down.
function low(rows) {
    return ["", "", ""].concat(rows)
}

function repeat(row, times) {
    var rows = []
    for (var i = 0; i < times; i++)
        rows.push(row)
    return rows
}

