// Bullets are this many dots across and tall, nearly the height of a line.
var bulletSize = 15

function glyph(character) {
    return glyphs[aliases[character] || character]
}

function glyphWidth(rows) {
    var width = 0
    for (var i = 0; i < rows.length; i++)
        width = Math.max(width, rows[i].length)
    return width
}

// How many dots wide a text is. Characters without a glyph are spaces.
function width(text) {
    var total = 0
    for (var i = 0; i < text.length; i++) {
        var rows = glyph(text.charAt(i))
        total += (rows ? glyphWidth(rows) : space) + (i > 0 ? gap : 0)
    }
    return total
}

// Adds a row of a pattern to `runs` as [x, y, length] for each stretch of lit dots.
function addRuns(runs, row, x, y) {
    var start = -1
    for (var i = 0; i <= row.length; i++) {
        var lit = i < row.length && row.charAt(i) === "#"
        if (lit && start < 0) {
            start = i
        } else if (!lit && start >= 0) {
            runs.push([x + start, y, i - start])
            start = -1
        }
    }
}

// The lit dots of a text as runs, [x, y, length], with the top of a capital at y = 0.
function runs(text) {
    var result = []
    var x = 0
    for (var i = 0; i < text.length; i++) {
        var rows = glyph(text.charAt(i))
        if (rows) {
            for (var y = 0; y < rows.length; y++)
                addRuns(result, rows[y], x, y)
        }
        x += (rows ? glyphWidth(rows) : space) + gap
    }
    return result
}

// A bullet as rows of its box: a disc, or a diamond for express, with the
// route's dots left unlit. `bullet` is the Board's bullet id, like "6" or "6d".
function bulletRows(bullet) {
    var diamond = bullet.length > 1 && bullet.charAt(bullet.length - 1) === "d"
    var middle = (bulletSize - 1) / 2
    var route = (diamond ? diamondGlyphs : bulletGlyphs)[bullet.charAt(0)] || []  // shuttles and "SIR" are an S
    var left = Math.floor((bulletSize - glyphWidth(route)) / 2)
    var top = Math.floor((bulletSize - route.length) / 2)
    var rows = []
    for (var y = 0; y < bulletSize; y++) {
        var row = ""
        for (var x = 0; x < bulletSize; x++) {
            var dx = Math.abs(x - middle), dy = Math.abs(y - middle)
            var inside = diamond ? dx + dy <= middle : dx * dx + dy * dy <= 7.5 * 7.5
            var cut = (route[y - top] || "").charAt(x - left) === "#"
            row += inside && !cut ? "#" : "."
        }
        rows.push(row)
    }
    return rows
}

function bulletRuns(bullet) {
    var result = []
    bulletRows(bullet).forEach(function (row, y) { addRuns(result, row, 0, y) })
    return result
}

// What the signs show for terminals too long for them. Only the first is from
// a photo; add the rest as they are seen.
var terminals = {
    "Flatbush Av-Brooklyn College": "Flatbush Av-Bklyn Col",
}

// For the others, the MTA's usual short forms, tried in this order, one more
// at a time, until the name fits.
var shortenings = [
    ["Brooklyn", "Bklyn"], ["College", "Col"], ["Center", "Ctr"], ["Boulevard", "Blvd"], ["Parkway", "Pkwy"],
    ["Heights", "Hts"], ["Square", "Sq"], ["Junction", "Jct"], ["Gardens", "Gdns"], ["Park", "Pk"],
]

// A name with as few of the shortenings as make it fit in `dots`, or "" if they can't.
function shortened(name, dots) {
    for (var i = 0; i < shortenings.length && width(name) > dots; i++)
        name = name.replace(new RegExp("\\b" + shortenings[i][0] + "\\b", "g"), shortenings[i][1])
    if (width(name) > dots)
        name = name.replace(/ (Av|St|Rd|Pl)s?$/, "")  // "Far Rockaway-Mott"
    return width(name) <= dots ? name : ""
}

// A terminal's name as it fits in `dots`: whole if it can be, then abbreviated,
// then without its last parts ("Whitehall St" for "Whitehall St-South Ferry"),
// and cut short as a last resort.
function fit(name, dots) {
    if (width(name) <= dots)
        return name
    if (terminals[name] && width(terminals[name]) <= dots)
        return terminals[name]
    var parts = name.split("-")
    for (var count = parts.length; count > 0; count--) {
        var text = shortened(parts.slice(0, count).join("-"), dots)
        if (text)
            return text
    }
    text = parts[0]
    while (text && width(text) > dots)
        text = text.slice(0, -1).replace(/[\s\/]+$/, "")
    return text
}
